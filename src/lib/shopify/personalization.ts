/* ── Motifs ───────────────────────────────────────────────────────── */

export interface MotifOption {
  value: string;
  label: string;
}

/**
 * Live motif catalogue for Dots and Emblem.
 *
 * Built directly from the auto-generated motif keys (one per SVG in
 * design/motifs/, generated by scripts/generate-motifs.mjs). The key
 * IS the verbatim filename, so it doubles as the displayed label —
 * there's no slugifying or translation. Camilla names the SVG exactly
 * how it should appear in the picker; add or remove SVGs and they
 * propagate here on the next build with no code change.
 */
export const MOTIFS: readonly MotifOption[] = ALL_MOTIF_KEYS.map((key) => ({
  value: key,
  label: key,
}));

/* ── Field types ──────────────────────────────────────────────────── */

interface FieldBase {
  /** Stable internal key. */
  key: string;
  /** Danish label shown on the form AND used as the line-item-property key on Shopify orders. */
  label: string;
  required?: boolean;
}

export interface ColorFieldDef extends FieldBase {
  type: "color";
  /** Defaults to NOONI_COLORS if omitted. */
  options?: readonly ColorOption[];
}

export interface TextFieldDef extends FieldBase {
  type: "text";
  maxLength?: number;
  placeholder?: string;
}

export interface SelectFieldDef extends FieldBase {
  type: "select";
  options: readonly { value: string; label: string }[];
}

/**
 * A mutually-exclusive choice between options, each of which can carry
 * its own sub-fields. Used by Dots: the customer picks either "Motiv"
 * or "Navn", and the corresponding sub-field renders below.
 */
export interface ChoiceFieldDef extends FieldBase {
  type: "choice";
  options: readonly {
    value: string;
    label: string;
    fields: readonly FieldDef[];
  }[];
}

export type FieldDef = ColorFieldDef | TextFieldDef | SelectFieldDef | ChoiceFieldDef;

export interface PersonalizationSchema {
  fields: readonly FieldDef[];
}

